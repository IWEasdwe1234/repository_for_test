# -- while문 --
print("\n-- while문 --")
# 조건이 참인 동안 계속 반복
# 조건이 거짓이 되면 멈춤
# for → range가 끝나면 자동으로 멈춤, while → 조건이 거짓이 되어야 멈춤
# 조건 변수를 반드시 바꿔줘야함(그렇지 않으면 무한루프, 무한루프는 Ctrl + C로 중단)

# 예시)
count = 1  # 1. 시작값 - 반복 전에 변수가 있는가
while count <= 3:  # 2. 종료 조건 - 언젠가 거짓이 되는가
    print(count)
    count += 1  # 3. 거짓 방향으로 변하는가


# -- 목표값 도달까지 반복 --
print("\n-- 목표값 도달까지 반복 --")
# 종료 조건에 !=를 사용하여 참이 아닌 동안 반복
# input과 함께 사용

# 예시)
answer = 7
guess = 0
while guess != answer:
    guess = int(input("정답 7: "))

print("\n정답입니다!")


# -- break로 반복 중단하기 --
print("\n-- break로 반복 중단하기 --")
# 반복 중에 break를 만나면 반복문 종료, 빠져나감

# 예시)
for i in range(1, 11):  # 1부터 시작해서 11직전까지의 값을 차례대로 i에 저장
    if i == 5:  # 만약 i 값이 5가 된다면
        break  # 반복문 즉시 종료
    print(i)  # i 출력 → 1, 2, 3, 4 (5에서 반복문이 종료되어 4까지만 출력)


# -- continue로 회차 건너뛰기 --
print("\n-- continue로 회차 건너뛰기 --")
# continue는 이번 회차에 조건에 맞으면 다음 회차로 건너뜀

for i in range(1, 7):  # 1부터 시작해서 7 직전까지의 값을 차례대로 i에 저장
    if i % 2 == 0:  # 2로 나눌 때 나머지가 0이면 (짝수 라면)
        continue  # 아래 코드를 실행하지 않고 다음 반복으로 넘어감
    print(i)  # i 출력 → 1, 3, 5 (짝수가 아닌 값(홀수) 출력됨)


# -- 사용자 입력(input)으로 반복 제어 --
print("\n-- 사용자 입력(input)으로 반복 제어 --")

while True:  # 조건이 True인 동안 계속 반복
    x = input("입력 (q=종료): ")  # 입력한 값을 x에 저장
    if x == "q":  # 만약 입력값이 "q"와 일치한다면
        break  # 반복문 종료
    print("입력:", x)  # 어떤 값을 입력했는지 출력


# -- 반복 속 조건 분기 --
print("\n-- 반복 속 조건 분기 --")

n = int(input("횟수: "))  # 입력한 값을 정수로 변환하여 n에 저장
for i in range(
    n
):  # n번(입력값 횟수) 반복하며 0부터 n-1까지의 인덱스를 i에 저장(현재 코드에서 i는 미사용)
    v = int(input("측정값: "))  # 입력한 값을 정수로 변환하여 v에 저장
    if v > 5:  # 만약 v값이 5보다 클 경우
        print(v, "상태 이상")  # 해당 조건을 만족한 v와 "상태 이상" 출력
    else:  # 위 조건(v > 5)이 거짓인 경우
        print(v, "정상")  # 해당 조건을 만족한 v와 "정상" 출력


# -- 누적과 조건의 결합 --
print("\n-- 누적과 조건의 결합 --")

total = 0
count = 0
for v in range(1, 11):  # 1부터 시작해서 11직전까지의 값을 차례대로 v에 저장
    if v > 5:  # 만약 v값이 5보다 큰 경우
        # 조건을 만족하는 v값은 6, 7, 8, 9, 10
        total += v  # total에 현재 v값을 더하여 다시 total에 저장(재할당)
        count += 1  # 조건을 만족할 때마다 count값 1씩 증가
print("합:", total, "개수:", count)


# -- 조건으로 반복 종료하기 --
print("\n-- 조건으로 반복 종료하기 --")

total = 0
i = 0
while True:  # 조건이 True인 동안 계속 반복
    i += 1  # i에 1을 더한 결과를 다시 i에 저장(재할당)
    total += i  # total에 증가된 i값을 더한 결과를 다시 total에 저장(재할당)
    if total > 100:  # total값이 100보다 큰 경우
        break  # 반복문 종료
print(i, "까지 합:", total)


# -- 최댓값, 최솟값 찾기 --
print("\n-- 최댓값, 최솟값 찾기 --")

first = int(input("1번째 :"))  # 입력값을 정수로 변환(형변환)한 뒤 first에 저장(할당)
max_value = first  # first 값을 max_value에 저장(할당)
for i in range(
    4
):  # 4번 반복하여 0부터 3까지의 값을 차례대로 i에 저장 (인덱스로 사용 가능하지만 현재 코드에서 i는 미사용)
    v = int(input("다음: "))  # 입력값을 정수로 변환(형변환)한 뒤 v에 저장(할당)
    if v > max_value:  # 만약 v가 현재까지의 최댓값인 max_value보다 큰 경우
        max_value = v  # v를 max_value에 저장(재할당)
print("최댓값:", max_value)

