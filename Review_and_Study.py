print("\n-- range() --")
# ()안에 원하는 값 만큼 연속된 숫자를 생성
# ,(콤마)를 사용하면 일정 범위의 값이나 건너 뛰는 값을 설정 가능

# 예시)
for i in range(4):  # 네 차례 동안 값을 하나씩 가져와 i에 넣고 아래 코드 실행
    print(i)  # 0, 1, 2, 3 (0부터 순서대로 4개)
print("\n")

for i in range(2, 5):
    # 2부터 5 직전까지(세 차례) 값을 하나씩 가져와 i에 넣고 아래 코드 실행
    print(i)  # 2, 3, 4 (2부터 총 3번 출력)
print("\n")

for i in range(1, 10, 2):
    # 1부터 10 직전까지 2씩 건너 뛰며 값을 가져와 i에 넣고 아래 코드를 실행
    print(i)  # 1, 3, 5, 7, 9 (1부터 시작해서 2씩 증가하여 10 직전까지)
print("\n")

for i in range(3, 0, -1):
    # 3부터 0 직전(1)까지 1씩 작아지며 값을 가져와 i에 넣고 아래 코드 실행
    print(i)  # 3, 2, 1 (3부터 시작해서 1씩 감소하여 0 직전까지)
print("\n")

# 활용 (반복 횟수 직접 입력)
num = int(input("반복 횟수 입력: "))
# 변수 값은 숫자(정수)이기 때문에 문자열인 input()을 int로 형변환
for i in range(num):  # 입력한 횟수동안 반복
    print("반복하고 싶은 글자")  # 반복할 때 마다 출력됨
print("반복 종료")  # for문의 코드가 종료되면 "반복 종료" 출력

