# -- 플래그 변수 활용 --
print("\n-- 플래그 변수 활용 --")

found = False  # 이상값 발견 여부를 나타내는 False를 found에 저장(할당)
for v in [70, 92, 65]:  # 리스트의 값을 차례대로 v에 저장(할당)
    if v > 80:  # 만약 v값이 80보다 큰 경우
        found = True  # 이상값을 발견했음을 나타내는 True를 found에 저장(재할당)
if found:  # 만약 found값이 True인 경우
    print("이상값 있음")  # "이상값 있음" 출력
else:  # found값이 False인 경우
    print("모두 정상")  # "모두 정상" 출력

# -- 반복문 안에서 조건 걸기 --
print("\n-- 반복문 안에서 조건 걸기 --")

temp = [25, 32, 28, 35, 27]  # 리스트를 temp에 저장(할당)
for t in temp:  # temp 리스트의 값을 차례대로 t에 저장(할당)
    if t > 30:  # 만약 t값이 30보다 큰 경우
        print(t, "고온주의")  # 해당 조건을 만족한 t값과 "고온주의" 출력

# -- 조건에 맞는 값만 골라내기 --
print("\n-- 조건에 맞는 값만 골라내기 --")

temps = [25, 32, 28, 35, 19]  # 리스트를 temps에 저장(할당)
